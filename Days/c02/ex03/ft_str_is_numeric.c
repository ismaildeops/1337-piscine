#include<stdio.h>
int ft_str_is_numeric(char *str)
{
    int i = 0;
    int j = 0;
    while (str[j] != '\0')
    {
        j++;
    }
    while ('0' <= str[i] && str[i] <= '9')
    {
        i++;
    }
    if (i == j)
    {
        return 1;
    }
    else
        return 0;
    
}