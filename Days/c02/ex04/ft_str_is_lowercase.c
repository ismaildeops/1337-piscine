int     ft_str_is_lowercase(char *str)
{
    int     i;
    
    i = 0;
    while (str[i] != '\0')
    {
        if ('A' <= str[i] && str[i] <= 'Z')
        {
            return 1;
        }
        else
        {
            i++;
        }  
    }
    return 0;   
}