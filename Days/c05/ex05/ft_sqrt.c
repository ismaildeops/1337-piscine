int ft_sqrt(int nb)
{
    int n = 0;
    if (nb < 0)
    {
        return 0;
    }
    while (n * n != nb && n * n < nb)
    {
        n++;
    }
    if (n * n == nb)
    {
        return n;
    }
    return 0;
}
